const DICTS: Record<Lang, Dict> = { 'kk-KZ': kz, 'ru-RU': ru, 'en-US': en as Dict };

/** Resolve the device language to a supported AppLanguage (defaults to en-US). */
export function getDeviceLanguage(): Lang {
  try {
    const loc = Localization.getLocales()[0];
    return normalizeLanguage(loc?.languageTag ?? loc?.languageCode) ?? DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

function lookup(lang: Lang, key: string): string {
  return DICTS[lang][key] ?? (en as Dict)[key] ?? key;
}

/** Pure translator for a given language — also usable at non-React call sites. */
export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  return interpolate(lookup(lang, key), vars);
}

/** Plural category for `count` in `lang` (cardinal). Falls back to one/other if Intl is unavailable. */
function pluralCategory(lang: Lang, count: number): string {
  try {
    return new Intl.PluralRules(lang).select(count);
  } catch {
    return count === 1 ? 'one' : 'other';
  }
}

/** Pluralized translate: resolves `${keyBase}.${category}` (falls back to `.other`). `count` is also
 *  passed as an interpolation var so the dict can render `{count}`. */
export function translateCount(lang: Lang, keyBase: string, count: number, vars?: Record<string, string | number>): string {
  const cat = pluralCategory(lang, count);
  const merged = { count, ...(vars ?? {}) };
  const exact = DICTS[lang][`${keyBase}.${cat}`] ?? (en as Dict)[`${keyBase}.${cat}`];
  const other = DICTS[lang][`${keyBase}.other`] ?? (en as Dict)[`${keyBase}.other`];
  return interpolate(exact ?? other ?? keyBase, merged);
}

// ── Locale-aware formatting (driven by the APP language, NOT the device locale) ────────────────
function toDate(value: Date | string | number): Date {
  return value instanceof Date ? value : new Date(value);
}

const DEFAULT_DATE_OPTS: Intl.DateTimeFormatOptions = { year: 'numeric', month: 'short', day: 'numeric' };
const DEFAULT_DATETIME_OPTS: Intl.DateTimeFormatOptions = {
  year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
};

/** Format a date using the app language (e.g. ru-RU → "28 июн. 2026"). Falls back to en-US. */
export function formatDate(lang: Lang, value: Date | string | number, options?: Intl.DateTimeFormatOptions): string {
  const d = toDate(value);
  try {
    return new Intl.DateTimeFormat(lang, options ?? DEFAULT_DATE_OPTS).format(d);
  } catch {
    return new Intl.DateTimeFormat('en-US', options ?? DEFAULT_DATE_OPTS).format(d);
  }
}

/** Format a date+time using the app language. Falls back to en-US. */
export function formatDateTime(lang: Lang, value: Date | string | number, options?: Intl.DateTimeFormatOptions): string {
  const d = toDate(value);
  try {
    return new Intl.DateTimeFormat(lang, options ?? DEFAULT_DATETIME_OPTS).format(d);
  } catch {
    return new Intl.DateTimeFormat('en-US', options ?? DEFAULT_DATETIME_OPTS).format(d);
  }
}

/** Format a number using the app language grouping/digits. Falls back to en-US. */
export function formatNumber(lang: Lang, value: number, options?: Intl.NumberFormatOptions): string {
  try {
    return new Intl.NumberFormat(lang, options).format(value);
  } catch {
    return String(value);
  }
}

// ── Enum / type → localized label mappers (no raw enum values in the UI) ───────────────────────
export function formatChallengeCategory(lang: Lang, category: string): string {
  return lookup(lang, `category.${category}`);
}
export function formatChallengeMode(lang: Lang, mode: string): string {
  return lookup(lang, `mode.${mode}`);
}
/** Server submission status → label. Accepts the server statuses + 'not-submitted' sentinel. */
export function formatSubmissionStatus(lang: Lang, status: string): string {
  const key =
    status === 'pending_verification' ? 'status.pending'
    : status === 'verified' ? 'status.verified'
    : status === 'rejected' ? 'status.rejected'
    : status === 'submitted' ? 'status.submitted'
    : 'status.notSubmitted';
  return lookup(lang, key);
}
export function formatMemberRole(lang: Lang, role: string): string {
  return lookup(lang, `role.${role}`);
}
/** Localized "{n} days" via plurals. */
export function formatDays(lang: Lang, count: number): string {
  return translateCount(lang, 'days', count);
}

// ── React binding ────────────────────────────────────────────────────────────────────────────
type I18nContextValue = {
  lang: Lang;
  isRTL: boolean;
  /** Change + persist the active language (applies immediately, no restart). */
  setLanguage: (lang: Lang) => void;
  t: (key: I18nKey, vars?: Record<string, string | number>) => string;
  /** Pluralized translate for counts (Intl.PluralRules). */
  tn: (keyBase: string, count: number, vars?: Record<string, string | number>) => string;
  /** App-language date formatter (not device locale). */
  fmtDate: (value: Date | string | number, options?: Intl.DateTimeFormatOptions) => string;
  /** App-language date+time formatter. */
  fmtDateTime: (value: Date | string | number, options?: Intl.DateTimeFormatOptions) => string;
  /** App-language number formatter. */
  fmtNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getDeviceLanguage);

  // Load the persisted choice once on mount (overrides the device fallback if present).
  useEffect(() => {
    let active = true;
    getStoredLanguage().then((stored) => {
      if (active && stored) setLangState(stored);
    });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = useCallback((next: Lang) => {
    setLangState(next);
    void storeLanguage(next);
  }, []);

  const t = useCallback((key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
  const tn = useCallback(
    (keyBase: string, count: number, vars?: Record<string, string | number>) => translateCount(lang, keyBase, count, vars),
    [lang],
  );
  const fmtDate = useCallback((v: Date | string | number, o?: Intl.DateTimeFormatOptions) => formatDate(lang, v, o), [lang]);
  const fmtDateTime = useCallback((v: Date | string | number, o?: Intl.DateTimeFormatOptions) => formatDateTime(lang, v, o), [lang]);
  const fmtNumber = useCallback((v: number, o?: Intl.NumberFormatOptions) => formatNumber(lang, v, o), [lang]);
  const value = useMemo<I18nContextValue>(
    () => ({ lang, isRTL: LANG_IS_RTL[lang], setLanguage, t, tn, fmtDate, fmtDateTime, fmtNumber }),
    [lang, setLanguage, t, tn, fmtDate, fmtDateTime, fmtNumber],
  );
  return createElement(I18nContext.Provider, { value }, children);
}

/** Access `t()` / `tn()` + current language. Falls back to device language outside a provider. */
export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (ctx) return ctx;
  const lang = getDeviceLanguage();
  return {
    lang,
    isRTL: LANG_IS_RTL[lang],
    setLanguage: () => {},
    t: (key, vars) => translate(lang, key, vars),
    tn: (keyBase, count, vars) => translateCount(lang, keyBase, count, vars),
    fmtDate: (v, o) => formatDate(lang, v, o),
    fmtDateTime: (v, o) => formatDateTime(lang, v, o),
    fmtNumber: (v, o) => formatNumber(lang, v, o),
  };
}

/** Convenience hook returning just the translator. */
export function useT(): I18nContextValue['t'] {
  return useI18n().t;
}
